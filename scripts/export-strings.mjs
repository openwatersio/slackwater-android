import { requireSupportedNode } from './sync-upstream.mjs';
import { readFile, writeFile, readdir, mkdir, unlink } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

requireSupportedNode(process.versions.node);

const root = fileURLToPath(new URL('../', import.meta.url));
const generatedName = 'ios_strings.xml';
const ownsXML = text => text.includes('<!-- Generated by scripts/export-strings.mjs ') || text.includes('<!-- Generated from scripts/translations/android/');

export function localeDirectory(locale) {
 if (!/^[a-z]{2,3}(?:-[A-Z]{2})?$/.test(locale)) throw Error(`Invalid locale: ${locale}`);
 if (locale === 'en') return 'values';
 const [language, region] = locale.split('-');
 return language.length === 3 || language === 'gd' || language === 'ga'
  ? `values-b+${locale.replaceAll('-', '+')}`
  : `values-${language}${region ? `-r${region}` : ''}`;
}

export function androidFormat(value) {
 let index = 0;
 return value.replace(/%(?:%|(?:(\d+)\$)?([-+ 0#]*)(\d*(?:\.\d+)?)(?:ll|l)?([@dfs]))|%/g,
  (match, position, flags, width, type) => {
   if (match === '%%') return match;
   if (!type) throw Error(`Unsupported format in ${value}`);
   const argument = position ? Number(position) : ++index;
   if (argument < 1) throw Error(`Unsupported format in ${value}`);
   return `%${argument}$${flags}${width}${type === '@' ? 's' : type}`;
  });
}

function signature(value) {
 return [...value.matchAll(/%(\d+)\$[-+ 0#]*\d*(?:\.\d+)?([sdf])/g)]
  .map(m => `${m[1]}:${m[2]}`).sort().join(',');
}

function xmlText(value) {
 return '"' + value.replaceAll('\\', '\\\\').replaceAll('&', '&amp;').replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;').replaceAll("'", "\\'").replaceAll('"', '\\"')
  .replaceAll('\n', '\\n').replaceAll('\t', '\\t') + '"';
}

export function renderResource(name, key, entry, locale) {
 if (!/^[a-z][a-z0-9_]*$/.test(name)) throw Error(`Invalid resource name: ${name}`);
 const source = entry.localizations?.en;
 const base = source?.variations?.plural?.other?.stringUnit?.value ?? source?.stringUnit?.value ?? key;
 const expected = signature(androidFormat(base));
 const translated = entry.localizations?.[locale];
 const localization = translated ?? (locale === 'en' ? { stringUnit: { state: 'translated', value: key } } : null);
 if (!localization) return null;
 const format = unit => {
  if (!unit || (locale !== 'en' && unit.state !== 'translated')) return null;
  const result = androidFormat(unit.value);
  if (signature(result) !== expected) throw Error(`Incompatible placeholders: ${name} (${locale})`);
  return xmlText(result);
 };
 if (localization.variations) {
  const plural = localization.variations.plural;
  if (!plural?.other) throw Error(`Unsupported variations: ${name} (${locale})`);
  const items = [];
  for (const quantity of ['zero', 'one', 'two', 'few', 'many', 'other']) {
   if (!plural[quantity]) continue;
   const text = format(plural[quantity].stringUnit);
   if (text === null) return null;
   items.push(`        <item quantity="${quantity}">${text}</item>`);
  }
  return `    <plurals name="${name}">\n${items.join('\n')}\n    </plurals>`;
 }
 const text = format(localization.stringUnit);
 return text === null ? null : `    <string name="${name}">${text}</string>`;
}

export function renderAndroidResource(name, source, translated, locale) {
 if (!/^[a-z][a-z0-9_]*$/.test(name)) throw Error(`Invalid resource name: ${name}`);
 const text = (value, expected) => {
  if (typeof value !== 'string') throw Error(`Missing Android translation: ${name}`);
  const formatted = androidFormat(value.replaceAll("\\'", "'"));
  if (signature(formatted) !== signature(androidFormat(expected))) throw Error(`Incompatible placeholders: ${name}`);
  return xmlText(formatted);
 };
 if (typeof source === 'string') return `    <string name="${name}">${text(translated, source)}</string>`;
 if (Array.isArray(source)) {
  if (!Array.isArray(translated) || translated.length !== source.length) throw Error(`Incompatible array: ${name}`);
  return `    <string-array name="${name}">\n${translated.map((v, i) => `        <item>${text(v, source[i])}</item>`).join('\n')}\n    </string-array>`;
 }
 if (!translated || typeof translated !== 'object' || !translated.other) throw Error(`Missing plural other: ${name}`);
 if (locale) {
  for (const quantity of new Intl.PluralRules(locale).resolvedOptions().pluralCategories) {
   if (!(quantity in translated)) throw Error(`Missing ${locale} plural ${quantity}: ${name}`);
  }
 }
 const items = [];
 for (const quantity of Object.keys(translated)) {
  if (!['zero', 'one', 'two', 'few', 'many', 'other'].includes(quantity)) throw Error(`Invalid plural quantity: ${name}`);
  items.push(`        <item quantity="${quantity}">${text(translated[quantity], source.other)}</item>`);
 }
 return `    <plurals name="${name}">\n${items.join('\n')}\n    </plurals>`;
}

export async function exportStrings(projectRoot, check = false) {
 const lock = JSON.parse(await readFile(join(projectRoot, 'upstream.lock.json'), 'utf8'));
 const revision = lock.productDocs.commit;
 if (!/^[a-f0-9]{40}$/.test(revision)) throw Error('Unpinned localization source');
 const mapping = JSON.parse(await readFile(join(projectRoot, 'scripts/strings-map.json'), 'utf8'));
 const ios = join(projectRoot, 'vendor/slackwater-ios');
 const bytes = execFileSync('git', ['show', `${revision}:${mapping.catalog}`], { cwd: ios, maxBuffer: 16 * 1024 * 1024 });
 const catalog = JSON.parse(bytes);
 if (catalog.sourceLanguage !== 'en') throw Error('Unsupported source language');
 const locales = ['en', ...[...new Set(Object.values(catalog.strings).flatMap(e => Object.keys(e.localizations ?? {})).filter(l => l !== 'en'))].sort()];
 const outputs = new Map();
 outputs.set('app/src/main/res/xml/locales_config.xml', `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/export-strings.mjs from the pinned iOS locale list. -->\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n${locales.map(l => `    <locale android:name="${l}"/>`).join('\n')}\n</locale-config>\n`);
 const missing = {};
 const seen = new Set();
 for (const entry of mapping.entries) {
  if (seen.has(entry.name)) throw Error(`Duplicate mapped resource: ${entry.name}`);
  seen.add(entry.name);
  if (!catalog.strings[entry.key]) throw Error(`Missing iOS key: ${entry.key}`);
 }
 for (const locale of locales) {
  const resources = [];
  missing[locale] = [];
  for (const {name, key, english, overrides} of mapping.entries) {
   const override = locale === 'en' ? english : overrides?.[locale];
   if (override !== undefined && signature(androidFormat(override)) !== signature(androidFormat(english ?? key))) throw Error(`Incompatible override placeholders: ${name} (${locale})`);
   const rendered = override !== undefined
    ? renderResource(name, override, {}, 'en')
    : renderResource(name, key, catalog.strings[key], locale);
   if (rendered === null) missing[locale].push(name);
   else resources.push(rendered);
  }
  const contents = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/export-strings.mjs from ${lock.productDocs.repository}@${revision}. -->\n<resources>\n${resources.join('\n')}\n</resources>\n`;
  outputs.set(join('app/src/main/res', localeDirectory(locale), generatedName), contents);
 }
 let androidCount = 0;
 if (mapping.androidDirectory) {
  const directory = join(projectRoot, mapping.androidDirectory);
  const source = JSON.parse(await readFile(join(directory, 'en.json'), 'utf8'));
  const names = Object.keys(source);
  androidCount = names.length;
  for (const name of names) if (seen.has(name)) throw Error(`Duplicate shared/Android resource: ${name}`);
  const files = await readdir(directory);
  const expectedFiles = locales.map(l => l + '.json');
  if (files.some(f => !expectedFiles.includes(f))) throw Error('Unexpected Android translation locale');
  for (const locale of locales) {
   const translations = JSON.parse(await readFile(join(directory, locale + '.json'), 'utf8'));
   if (Object.keys(translations).length !== names.length || names.some(n => !(n in translations))) throw Error(`Incomplete Android translations: ${locale}`);
   const resources = names.map(name => renderAndroidResource(name, source[name], translations[name], locale));
   outputs.set(join('app/src/main/res', localeDirectory(locale), 'strings_android.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from ${mapping.androidDirectory}/${locale}.json. Edit the JSON source. -->\n<resources>\n${resources.join('\n')}\n</resources>\n`);
  }
 }
 if (check && Object.values(missing).some(names => names.length)) throw Error('Missing iOS translations; inspect strings-provenance.json and the pinned catalog');
 const provenance = {
  repository: lock.productDocs.repository, commit: revision, catalog: mapping.catalog,
  sha256: createHash('sha256').update(bytes).digest('hex'), locales,
  mappedResources: mapping.entries.length, androidResources: androidCount, missingTranslations: missing,
 };
 outputs.set('scripts/strings-provenance.json', JSON.stringify(provenance, null, 2) + '\n');
 const res = join(projectRoot, 'app/src/main/res');
 for (const dir of await readdir(res)) {
  if (!dir.startsWith('values')) continue;
  for (const filename of mapping.androidDirectory ? [generatedName, 'strings_android.xml'] : [generatedName]) {
   const relative = join('app/src/main/res', dir, filename);
   const files = await readdir(join(res, dir));
   if (!files.includes(filename) || outputs.has(relative)) continue;
   if (check) throw Error(`Unexpected generated translations: ${relative}`);
   const stalePath = join(projectRoot, relative);
   if (!ownsXML(await readFile(stalePath, 'utf8'))) throw Error(`Refusing to delete handwritten resource: ${relative}`);
   await unlink(stalePath);
  }
 }
 for (const [relative, contents] of outputs) {
  const path = join(projectRoot, relative);
  if (check) {
   let actual;
   try { actual = await readFile(path, 'utf8'); } catch { throw Error(`Missing generated translations: ${relative}`); }
   if (actual !== contents) throw Error(`Stale generated translations: ${relative}`);
  } else {
   if (relative.endsWith('.xml')) {
    let existing;
    try { existing = await readFile(path, 'utf8'); } catch (e) { if (e.code !== 'ENOENT') throw e; }
    if (existing !== undefined && !ownsXML(existing)) throw Error(`Refusing to overwrite handwritten resource: ${relative}`);
   }
   await mkdir(join(path, '..'), { recursive: true });
   await writeFile(path, contents);
  }
 }
 return provenance;
}

if (import.meta.main) {
 const args = process.argv.slice(2);
 if (args.some(a => a !== '--check')) throw Error('Usage: node scripts/export-strings.mjs [--check]');
 exportStrings(root, args.includes('--check')).then(p => console.log(`Verified ${p.mappedResources} shared strings in ${p.locales.length} locales at ${p.commit}.`))
  .catch(e => { console.error(e.message); process.exitCode = 1; });
}
